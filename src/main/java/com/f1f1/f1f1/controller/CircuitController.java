    @GetMapping("/circuits")
    public String circuits(Model model) {
        model.addAttribute("circuits", CIRCUIT_DB);
        return "circuits";
    }

    @GetMapping("/circuits/{id}")
    public String circuitDetail(@PathVariable String id, Model model) {
        Circuit c = CIRCUIT_DB.get(id);
        if (c == null) return "redirect:/circuits";
        model.addAttribute("circuit", c);
        return "circuit-detail";
    }

